#!/usr/bin/env python3
"""
export_bbmodel.py - writes Blockbench project files (blockbench/*.bbmodel) generated FROM the model json files.
The json in src/main/resources is the single source of truth; these files are a convenience copy for editing in Blockbench.
(After editing in Blockbench use File > Export > Block/Item model and copy the json over the original, keeping the element names.)

NOTE: these were generated by script and could not be opened in Blockbench in the build environment (no Blockbench available);
they follow the .bbmodel 'java_block' format, but treat them as best-effort.
"""
import base64
import os
import sys
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from common import *  # noqa


def uid(s):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "tuffsmp/" + s))


def export(name, is_block, tex_key):
    model = load_json(model_path(("block/" if is_block else "") + name))
    W, H = model["texture_size"]
    tex_path = os.path.join(TEX_BLOCK if is_block else TEX_ITEM, tex_key + ".png")
    with open(tex_path, "rb") as f:
        b64 = base64.b64encode(f.read()).decode()
    elements, outliner = [], []
    for i, el in enumerate(model["elements"]):
        eid = uid(f"{name}/{el['name']}")
        rot = [0, 0, 0]
        origin = [0, 0, 0]
        r = el.get("rotation")
        if r:
            origin = r["origin"]
            if r.get("axis"):
                rot[{"x": 0, "y": 1, "z": 2}[r["axis"]]] = r.get("angle", 0)
            else:
                rot = [r.get("x", 0), r.get("y", 0), r.get("z", 0)]
        faces = {}
        for f in FACES:
            if f in el["faces"]:
                u1, v1, u2, v2 = el["faces"][f]["uv"]
                faces[f] = {"uv": [u1 / 16 * W, v1 / 16 * H, u2 / 16 * W, v2 / 16 * H], "texture": 0}
            else:
                faces[f] = {"uv": [0, 0, 0, 0], "texture": None}
        elements.append({
            "name": el["name"], "box_uv": False, "rescale": False, "locked": False, "light_emission": 0, "render_order": "default",
            "allow_mirror_modeling": True, "from": el["from"], "to": el["to"], "autouv": 0, "color": i % 8, "origin": origin,
            "rotation": rot, "uuid": eid, "faces": faces, "type": "cube",
        })
        outliner.append(eid)
    bb = {
        "meta": {"format_version": "4.10", "model_format": "java_block", "box_uv": False},
        "name": name, "parent": "", "ambientocclusion": True, "front_gui_light": False,
        "resolution": {"width": W, "height": H},
        "elements": elements, "outliner": outliner,
        "textures": [{
            "path": "", "name": tex_key + ".png", "folder": "", "namespace": "shrinecraft", "id": "0", "particle": True,
            "render_mode": "default", "render_sides": "auto", "frame_time": 1, "frame_order_type": "loop", "frame_order": "",
            "frame_interpolate": False, "visible": True, "mode": "bitmap", "saved": True, "uuid": uid(name + "/tex"),
            "relative_path": "", "source": "data:image/png;base64," + b64,
        }],
        "display": model.get("display", {}),
    }
    ensure_dir(BLOCKBENCH_DIR)
    out = os.path.join(BLOCKBENCH_DIR, name + ".bbmodel")
    save_json(out, bb, indent=None)
    return out


def main():
    meta = load_json(os.path.join(ROOT, "tools", "model_materials.json"))
    for name, m in meta.items():
        export(name, m["block"], m["texture"])
    print("wrote %d .bbmodel files to blockbench/" % len(meta))


if __name__ == "__main__":
    main()
